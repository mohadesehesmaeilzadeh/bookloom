export const LANGUAGE = {
  FA: 'fa',
  EN: 'en',
}

export const DEFAULT_LANGUAGE = LANGUAGE.FA

export const languageOptions = [
  {
    value: LANGUAGE.FA,
    label: 'فارسی',
    description: 'چیدمان راست به چپ با متن فارسی.',
    dir: 'rtl',
    locale: 'fa-IR',
  },
  {
    value: LANGUAGE.EN,
    label: 'English',
    description: 'Left-to-right layout with English text.',
    dir: 'ltr',
    locale: 'en-US',
  },
]

export const languageValues = languageOptions.map((language) => language.value)

export const languageByValue = Object.fromEntries(
  languageOptions.map((language) => [language.value, language]),
)

export function isValidLanguage(value) {
  return languageValues.includes(value)
}

export function getLanguageMeta(language) {
  return languageByValue[language] ?? languageByValue[DEFAULT_LANGUAGE]
}

export function getDocumentLanguage() {
  if (typeof document === 'undefined') {
    return DEFAULT_LANGUAGE
  }

  return isValidLanguage(document.documentElement.dataset.language)
    ? document.documentElement.dataset.language
    : DEFAULT_LANGUAGE
}

function interpolate(template, values = {}) {
  if (typeof template === 'function') {
    return template(values)
  }

  return String(template).replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? values[key] : match
  ))
}

